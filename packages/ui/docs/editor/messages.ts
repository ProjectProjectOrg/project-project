const fill = (text: string, inputs: Readonly<Record<string, string>> = {}) =>
  text.replace(/\{(\w+)\}/g, (_, name: string) => inputs[name] ?? "")

export const editorMessages = Object.fromEntries(
  Object.entries(en).map(([key, text]) => [
    key,
    (inputs?: Readonly<Record<string, string>>) => fill(text, inputs)
  ])
) as unknown as EditorMessages
